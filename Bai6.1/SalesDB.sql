CREATE DATABASE IF NOT EXISTS SalesDB
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE SalesDB;

CREATE TABLE IF NOT EXISTS NhanVien (
	MaNV INT NOT NULL AUTO_INCREMENT,
	TenNV NVARCHAR(100) NOT NULL,
	SoDienThoai VARCHAR(15) NULL UNIQUE,
	ChucVu NVARCHAR(50) NULL,
	PRIMARY KEY (MaNV)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS KhachHang (
	MaKH INT NOT NULL AUTO_INCREMENT,
	TenKH NVARCHAR(100) NOT NULL,
	DienThoai VARCHAR(15) NULL UNIQUE,
	DiemTichLuy INT NOT NULL DEFAULT 0,
	PRIMARY KEY (MaKH),
	CONSTRAINT chk_khachhang_diem CHECK (DiemTichLuy >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SanPham (
	MaSP VARCHAR(20) NOT NULL,
	TenSP NVARCHAR(150) NOT NULL,
	GiaBan DECIMAL(18,2) NOT NULL,
	SoLuongTon INT NOT NULL,
	PRIMARY KEY (MaSP),
	CONSTRAINT chk_sanpham_gia CHECK (GiaBan > 0),
	CONSTRAINT chk_sanpham_ton CHECK (SoLuongTon >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS HoaDon (
	MaHD INT NOT NULL AUTO_INCREMENT,
	NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	MaNV INT NOT NULL,
	MaKH INT NULL,
	TongTien DECIMAL(18,2) NOT NULL,
	PRIMARY KEY (MaHD),
	CONSTRAINT chk_hoadon_tong CHECK (TongTien >= 0),
	CONSTRAINT fk_hoadon_nhanvien FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
	CONSTRAINT fk_hoadon_khachhang FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ChiTietHoaDon (
	MaHD INT NOT NULL,
	MaSP VARCHAR(20) NOT NULL,
	SoLuong INT NOT NULL,
	DonGia DECIMAL(18,2) NOT NULL,
	PRIMARY KEY (MaHD, MaSP),
	CONSTRAINT chk_chitiethoadon_soluong CHECK (SoLuong > 0),
	CONSTRAINT chk_chitiethoadon_dongia CHECK (DonGia > 0),
	CONSTRAINT fk_chitiethoadon_hoadon FOREIGN KEY (MaHD) REFERENCES HoaDon(MaHD),
	CONSTRAINT fk_chitiethoadon_sanpham FOREIGN KEY (MaSP) REFERENCES SanPham(MaSP)
) ENGINE=InnoDB;