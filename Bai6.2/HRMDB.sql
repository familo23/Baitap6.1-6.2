DELIMITER //
DROP TRIGGER IF EXISTS TR_BangChamCong_BeforeInsert//
DROP TRIGGER IF EXISTS TR_BangChamCong_BeforeUpdate//
DROP TRIGGER IF EXISTS TR_BangChamCong_BeforeDelete//
CREATE TRIGGER TR_BangChamCong_BeforeInsert
BEFORE INSERT ON BangChamCong FOR EACH ROW
BEGIN
	IF EXISTS (SELECT 1 FROM BangLuong WHERE MaNV = NEW.MaNV AND ThangNam = NEW.ThangNam) THEN
		SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Thang cham cong da duoc chot luong';
	END IF;
END//

CREATE TRIGGER TR_BangChamCong_BeforeUpdate
BEFORE UPDATE ON BangChamCong FOR EACH ROW
BEGIN
	IF EXISTS (SELECT 1 FROM BangLuong WHERE MaNV = OLD.MaNV AND ThangNam = OLD.ThangNam)
	   OR EXISTS (SELECT 1 FROM BangLuong WHERE MaNV = NEW.MaNV AND ThangNam = NEW.ThangNam) THEN
		SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Thang cham cong da duoc chot luong';
	END IF;
END//

CREATE TRIGGER TR_BangChamCong_BeforeDelete
BEFORE DELETE ON BangChamCong FOR EACH ROW
BEGIN
	IF EXISTS (SELECT 1 FROM BangLuong WHERE MaNV = OLD.MaNV AND ThangNam = OLD.ThangNam) THEN
		SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Thang cham cong da duoc chot luong';
	END IF;
END//
DELIMITER ;