SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS HRMDB
	CHARACTER SET utf8mb4
	COLLATE utf8mb4_unicode_ci;
USE HRMDB;

CREATE TABLE IF NOT EXISTS PhongBan (
	MaPB INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	TenPB NVARCHAR(100) NOT NULL,
	Mota NVARCHAR(255) NULL,
	CONSTRAINT UQ_PhongBan_TenPB UNIQUE (TenPB)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS NhanVien (
	MaNV INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	HoTen NVARCHAR(100) NOT NULL,
	NgaySinh DATETIME NULL,
	CCCD VARCHAR(20) NULL UNIQUE,
	MaPB INT NULL,
	LuongCoBan DECIMAL(18,2) NOT NULL,
	HeSoLuong FLOAT NOT NULL DEFAULT 1.0,
	CONSTRAINT CK_NhanVien_LuongCoBan CHECK (LuongCoBan > 0),
	CONSTRAINT CK_NhanVien_HeSoLuong CHECK (HeSoLuong > 0),
	CONSTRAINT FK_NhanVien_PhongBan FOREIGN KEY (MaPB) REFERENCES PhongBan(MaPB)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS BangChamCong (
	MaCong INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	MaNV INT NOT NULL,
	ThangNam VARCHAR(7) NOT NULL,
	SoNgayCong FLOAT NOT NULL DEFAULT 0,
	SoGioOT FLOAT NOT NULL DEFAULT 0,
	CONSTRAINT UQ_BangChamCong_NhanVien_Thang UNIQUE (MaNV, ThangNam),
	CONSTRAINT CK_BangChamCong_SoNgayCong CHECK (SoNgayCong >= 0 AND SoNgayCong <= 31),
	CONSTRAINT CK_BangChamCong_SoGioOT CHECK (SoGioOT >= 0),
	CONSTRAINT FK_BangChamCong_NhanVien FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS BangLuong (
	MaLuong INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	MaNV INT NOT NULL,
	ThangNam VARCHAR(7) NOT NULL,
	ThucLinh DECIMAL(18,2) NOT NULL,
	CONSTRAINT UQ_BangLuong_NhanVien_Thang UNIQUE (MaNV, ThangNam),
	CONSTRAINT FK_BangLuong_NhanVien FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV)
) ENGINE=InnoDB;

